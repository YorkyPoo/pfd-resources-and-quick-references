#!/usr/bin/env python3
"""Preview-build-only MkDocs hook.

Replaces scripts/mkdocs_post_build.py for the /preview/ build:

* writes a hard robots.txt (User-agent: * / Disallow: /)
* makes sure every emitted HTML page carries a noindex/nofollow robots meta
  (the theme override covers normal pages; this also covers 404.html and any
  page rendered from a template that does not extend overrides_preview/main.html)
* deletes the service worker and any sitemap/manifest artefacts, so the
  preview cannot register a cache on the shared origin.

It never runs for the live build because it is only listed in
mkdocs.preview.yml, which is generated by scripts/build_preview_cfg.py.
"""
import os
import re

META = '<meta name="robots" content="noindex, nofollow">'


def on_post_build(config, **kwargs):
    site_dir = config["site_dir"]

    # Hard block for crawlers at the preview prefix.
    with open(os.path.join(site_dir, "robots.txt"), "w", encoding="utf-8") as fh:
        fh.write("User-agent: *\nDisallow: /\n")

    # Belt-and-braces: every page gets the noindex meta.
    missing = 0
    for root, dirs, files in os.walk(site_dir):
        dirs[:] = [d for d in dirs if d not in (".git", "__pycache__")]
        for fn in files:
            if not fn.endswith(".html"):
                continue
            fp = os.path.join(root, fn)
            with open(fp, encoding="utf-8", errors="replace") as fh:
                html = fh.read()
            if re.search(r'name="robots"[^>]*noindex', html[:4000]):
                continue
            m = re.search(r"</head>", html, flags=re.I)
            if not m:
                continue
            html = html[: m.start()] + META + "\n" + html[m.start():]
            with open(fp, "w", encoding="utf-8") as fh:
                fh.write(html)
            missing += 1

    removed = []
    for name in ("sw.js", "sitemap.xml", "sitemap.xml.gz", "manifest.webmanifest"):
        p = os.path.join(site_dir, name)
        if os.path.exists(p):
            os.remove(p)
            removed.append(name)

    print(f"[preview] robots.txt=Disallow:/ ; injected noindex into {missing} page(s); "
          f"removed {removed}")
