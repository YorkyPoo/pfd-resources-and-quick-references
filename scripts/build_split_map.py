#!/usr/bin/env python3
"""Build audit/level-scan/split-map.yaml — the durable record of split rows.

WHY THIS FILE EXISTS
--------------------
A `held_level_correct` row is a site row that **splits a PEMS row the region
merges**. Its levels are right today only because both halves agree. That
pairing has so far lived in `alignment.json` (regenerated on every aligner run)
and in the hand `HELD` list inside `build_c2_scope.py`. Regenerate the aligner
and the knowledge is gone; write it only in a handoff note and it dies with the
first person who merges the rows. This script writes it down as data, and
`verify_pems_canonical.py` re-derives the invariant from the site pages on
every run so a split that stops agreeing FAILS instead of going quiet.

HOW `site_rows` IS DERIVED (not guessed)
----------------------------------------
For every `held_level_correct` row in `c2-scope.json` the PEMS key is
`(pems_page, pems_ordinal)`. The site rows that split that key are:

  1. every held row in `c2-scope.json` carrying the same key (two site pages may
     both hold one PEMS row — e.g. Airway Irritants and Smoke Inhalation both
     split p.153 row 2);
  2. every `shared_pems_row` row in `alignment.json` that names the key, either
     through `contained_in_pems` or through the `p.153 row 2` citation in its
     reason line (the aligner records one or the other, never both).

The matched holder of the PEMS row is **not** listed: it publishes the PEMS
row's own badge spread already, and including it would make the union test
vacuous by construction (it would add a level the split is not about).

`badge` comes from `pems_table.json` for the same key, never typed by hand.

Run: python3 scripts/build_split_map.py [--write] [--print]
"""
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "audit", "level-scan")
C2 = os.path.join(OUT, "c2-scope.json")
ALIGN = os.path.join(OUT, "alignment.json")
TABLE = os.path.join(OUT, "pems_table.json")
DEST = os.path.join(OUT, "split-map.yaml")

KEY_RE = re.compile(r"p\.(\d+) row (\d+)")


def row_key(value):
    """A site row label as a lookup key: ints stay ints, split labels stay str."""
    s = str(value).strip()
    return int(s) if s.isdigit() else s
HEADER = """\
# Durable record of the split rows: a site row that splits a PEMS row the
# region merges. Every entry is checked by scripts/verify_pems_canonical.py
# (check `c2.split_map`), which re-parses the named site rows on every run.
#
# Base level of a split is the PEMS row. `site_rows` are the site rows that
# split it. The invariant: the UNION of the levels published by site_rows
# must equal exactly the PEMS badge level and every level above it. A row that
# publishes `X` authorises X and above; MC in every cell is the full set;
# blank cells contribute nothing. If this map and the site pages disagree, the
# verifier fails and names the split — that is the point.
#
# Generated by scripts/build_split_map.py from c2-scope.json (the held rows),
# alignment.json (the shared_pems_row partners) and pems_table.json (the badge).
"""


def load():
    c2 = json.load(open(C2, encoding="utf-8"))
    align = json.load(open(ALIGN, encoding="utf-8"))
    table = json.load(open(TABLE, encoding="utf-8"))
    pems = {(r["page"], r["ordinal"]): r
            for d in table["pems_docs"] for r in d["rows"]}
    held = [r for r in c2["rows"] if r.get("disposition") == "held_level_correct"]
    return held, align, pems


def load_bindings():
    """(file, row-str) -> (pems_page, pems_ordinal) for the conversion's explicit cites."""
    import yaml
    path = os.path.join(OUT, "row-bindings.yaml")
    if not os.path.exists(path):
        return {}
    doc = yaml.safe_load(open(path, encoding="utf-8")) or {}
    out = {}
    for rec in doc.get("bindings") or []:
        if rec.get("pems_page") is None or rec.get("pems_ordinal") is None:
            continue
        out[(rec["file"], str(rec["row"]))] = (int(rec["pems_page"]),
                                              int(rec["pems_ordinal"]))
    return out


def split_partners(key, held, align, bindings, own=None):
    """Every site row that splits `key`, derived from the artifacts, minus rows the
    conversion now cites to a different PEMS row.

    A row that `row-bindings.yaml` explicitly bounds to another PEMS row is not part of
    this split any more: the 2026-11-20 row-structure pass split it, and each part cites
    the PEMS row that prints it (e.g. Pneumothorax r12's fluid bolus is p.113#4, not
    p.243#4). Listing it here would fail the union test — correctly — and would describe
    the page wrongly.
    """
    rows = {(r["file"], r["row"]) for r in held
            if (r["pems_page"], r["pems_ordinal"]) == key}
    for page in align["pages"]:
        for r in page["rows"]:
            if r.get("reason_kind") != "shared_pems_row":
                continue
            ci = r.get("contained_in_pems") or {}
            named = (ci.get("pems_page"), ci.get("pems_ordinal")) == key
            if not named:
                named = key in [(int(p), int(o))
                                for p, o in KEY_RE.findall(r.get("reason") or "")]
            if named:
                rows.add((page["site_page"], row_key(r["site_row"])))
    excluded = sorted((f, n) for f, n in rows
                      if bindings.get((f, str(n))) not in (None, key))
    # the row that DEFINES this entry stays in its own split: an explicit citation to
    # another row with the same badge spread does not remove it (the union still has to
    # add up to this PEMS row's levels, and the verifier names the entry by that row).
    excluded = [e for e in excluded if e != own]
    return sorted(rows - set(excluded)), excluded


def slug(rel):
    base = os.path.basename(rel)
    base = re.sub(r"\.md$", "", base)
    base = re.sub(r"^\d+_", "", base)
    base = re.sub(r"_PROC$", "", base)
    return re.sub(r"_+", "-", base).lower()


def build():
    held, align, pems = load()
    bindings = load_bindings()
    entries = []
    for r in held:
        key = (r["pems_page"], r["pems_ordinal"])
        p = pems.get(key)
        if p is None:
            raise SystemExit(f"pems_table.json has no row {key} for {r['file']} row {r['row']}")
        badge = (p.get("badge_tokens") or [None])[0]
        if not badge:
            raise SystemExit(f"PEMS row {key} has no badge token")
        partners, excluded = split_partners(key, held, align, bindings,
                                            own=(r["file"], r["row"]))
        if (r["file"], r["row"]) not in partners:
            raise SystemExit(f"{r['file']} row {r['row']} is not in its own split")
        if len(partners) == 1:
            note = ("degenerate split — only one site row publishes this PEMS row "
                    "(the site prints one row where PEMS prints one); recorded for symmetry")
        else:
            note = (f"site splits one PEMS row across {len(partners)} site rows; "
                    f"they split it at the level, not the text")
        if excluded:
            note += (" — excluded because `row-bindings.yaml` now cites it to a different "
                     "PEMS row: " + ", ".join(f"{os.path.basename(f)} r{n}" for f, n in excluded))
        entries.append({
            "id": f"{slug(r['file'])}-r{r['row']}",
            "pems": {"page": key[0], "ordinal": key[1], "badge": badge},
            "site_rows": [{"file": f, "row": n} for f, n in partners],
            "note": note,
        })
    ids = [e["id"] for e in entries]
    if len(ids) != len(set(ids)):
        raise SystemExit(f"duplicate split ids: {ids}")
    return entries


def dump(entries):
    import yaml

    class D(yaml.SafeDumper):
        pass

    def str_rep(dumper, data):
        return dumper.represent_scalar("tag:yaml.org,2002:str", data)

    D.add_representer(str, str_rep)
    body = yaml.dump({"splits": entries}, Dumper=D, sort_keys=False,
                     default_flow_style=False, allow_unicode=True, width=4096)
    return HEADER + body


def main():
    entries = build()
    text = dump(entries)
    print(f"splits derived: {len(entries)}")
    for e in entries:
        print(f"  {e['id']:38s} PEMS p.{e['pems']['page']}#{e['pems']['ordinal']} "
              f"{e['pems']['badge']:3s} <- {len(e['site_rows'])} site rows: "
              + ", ".join(f"{os.path.basename(s['file'])} r{s['row']}" for s in e["site_rows"]))
    if "--print" in sys.argv:
        print(text)
    if "--write" in sys.argv:
        with open(DEST, "w", encoding="utf-8") as fh:
            fh.write(text)
        print("\nwrote", DEST, f"({len(text)} bytes)")


if __name__ == "__main__":
    main()
