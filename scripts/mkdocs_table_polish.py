"""
Post-process hook: tidy PROSE tables (fx chassis) at build time.

Why here instead of the markdown: docs/fire-ems-references/initial-alarm-company-assignments.md
is GENERATED by scripts/port_reference.py from the vault note "Initial Alarm Company
Assignments". The vault is the owner's authoring surface, so the literal "- " bullets inside
its table cells are correct there — but a pipe table cannot hold a markdown list, so MkDocs
renders "- 📻 Switch to assigned TAC channel" as TEXT with a hyphen. On a phone the owner read
that as stray dashes ("there is at least one extra '-'"). Editing the exported .md would be
erased by the next re-port, so the cleanup lives where it cannot be clobbered: build time.

Two transforms, both idempotent, both confined to the fx table region:
  1. a dash acting as a bullet marker inside a cell becomes a real bullet character
  2. the "Unit - Role" label in the sticky column breaks onto two lines instead of
     stranding "First Engine -" at the end of a 104px column

Nothing else on the page is touched; sc/dz chassis are left alone because their cells are
one-character bullets, not prose.
"""
import re

BULLET = "•"


def _cell_lines_to_bullets(html: str) -> str:
    out = []
    for part in re.split(r"(<br\s*/?>)", html):
        if part.lower().startswith("<br"):
            out.append(part)
        else:
            # the vault note uses BOTH "- 📻" and glued "-📻" forms, so the space is optional
            out.append(re.sub(r"^[-\u2013\u2014]\s*(?=\S)", BULLET + " ", part))
    return "".join(out)


def _label_to_two_lines(html: str) -> str:
    # "First Engine - Fire Attack" -> "First Engine<br>Fire Attack" (single split, leftmost)
    return re.sub(r"\s+[-\u2013]\s+", "<br>", html, count=1)


def _polish_table(m: re.Match) -> str:
    head, body, tail = m.group(1), m.group(2), m.group(3)
    rows = re.split(r"(<tr>.*?</tr>)", body, flags=re.S)
    for i, row in enumerate(rows):
        if not row.startswith("<tr>"):
            continue
        cells = re.split(r"(<t[dh][^>]*>.*?</t[dh]>)", row, flags=re.S)
        for j, cell in enumerate(cells):
            mm = re.match(r"(<t[dh][^>]*>)(.*?)(</t[dh]>)", cell, flags=re.S)
            if not mm:
                continue
            open_tag, inner, close_tag = mm.groups()
            # The source ends several cells with a dangling "<br>" before the pipe, which
            # paints an empty bullet line at the bottom of the row (the owner's "extra -").
            inner = re.sub(r"^\s*<br\s*/?>\s*", "", inner)
            inner = re.sub(r"\s*<br\s*/?>\s*$", "", inner)
            inner = _cell_lines_to_bullets(inner)
            # re.split with a capture group puts cell 0 at index 1, not 2
            if "td" in open_tag and j == 1:  # first data cell = sticky unit label
                inner = _label_to_two_lines(inner)
            cells[j] = open_tag + inner + close_tag
        rows[i] = "".join(cells)
    return head + "".join(rows) + tail


def on_page_content(html, page, **kwargs):
    # only inside the fx chassis; the table may be a sibling of the wrapper or nested in
    # Material's .md-typeset__table, so match the whole region generously.
    pat = re.compile(r'(<div class="fx-wrap[^"]*"[^>]*>)(.*?)(</div>)', flags=re.S)
    if "fx-wrap" not in html:
        return html
    return pat.sub(_polish_table, html)
